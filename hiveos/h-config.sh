#!/usr/bin/env bash
set -u

# This file is sourced by HiveOS' generic /hive/miners/custom/h-config.sh.
# It must generate the selected custom miner configuration immediately.
# The generic dispatcher owns miner_ver/miner_config_gen callbacks.

pepew_package_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
pepew_conf_file="${CUSTOM_CONFIG_FILENAME:-${pepew_package_dir}/config.txt}"
pepew_setup_file="${pepew_package_dir}/setup.txt"
pepew_diagnostic_log="${pepew_package_dir}/pepepow-debug.log"
pepew_proxy_log="/var/log/miner/custom/PepeW-Miner-v1.0.3-HiveOS/stratum-proxy.log"
pepew_proxy_port="${PEPEPOW_PROXY_PORT:-49333}"

# miner-run normally has wallet.conf in scope. Source it only for direct tests.
if [[ -z "${CUSTOM_URL:-}" && -r /hive-config/wallet.conf ]]; then
  # shellcheck disable=SC1091
  source /hive-config/wallet.conf
fi

pepew_pool="${CUSTOM_URL:-}"
pepew_user="${CUSTOM_TEMPLATE:-}"
pepew_pass="${CUSTOM_PASS:-x}"
pepew_extra_raw="${CUSTOM_USER_CONFIG:-}"

if [[ -z "${pepew_pool}" ]]; then
  echo "HiveOS pool URL is missing (CUSTOM_URL)" >&2
  return 1 2>/dev/null || exit 1
fi
if [[ -z "${pepew_user}" ]]; then
  echo "HiveOS wallet/template is missing (CUSTOM_TEMPLATE)" >&2
  return 1 2>/dev/null || exit 1
fi
if [[ ! "${pepew_proxy_port}" =~ ^[0-9]+$ ]] || (( pepew_proxy_port < 1024 || pepew_proxy_port > 65535 )); then
  echo "Invalid PEPEPOW_PROXY_PORT: ${pepew_proxy_port}" >&2
  return 1 2>/dev/null || exit 1
fi

pepew_args=(
  "-o" "stratum+tcp://127.0.0.1:${pepew_proxy_port}"
  "-u" "${pepew_user}"
  "-p" "${pepew_pass}"
  "--diagnostic-log" "${pepew_diagnostic_log}"
)

if [[ "${PEPEW_DIAGNOSTIC:-0}" == "1" ]]; then
  pepew_args+=("--diagnostic")
fi

if [[ -n "${pepew_extra_raw}" ]]; then
  # HiveOS exposes this as an expert field. Preserve quoted argument groups.
  eval "pepew_extra=( ${pepew_extra_raw} )"
  pepew_args+=("${pepew_extra[@]}")
fi

mkdir -p "${pepew_package_dir}" "$(dirname "${pepew_proxy_log}")"
pepew_tmp_conf="${pepew_conf_file}.tmp.$$"
{
  echo "# Generated by PepeW Miner HiveOS integration"
  printf 'PEPEPOW_ARGS=('
  printf ' %q' "${pepew_args[@]}"
  echo ' )'
  printf 'PEPEPOW_UPSTREAM=%q\n' "${pepew_pool}"
  printf 'PEPEPOW_PROXY_LOG=%q\n' "${pepew_proxy_log}"
  printf 'PEPEPOW_PROXY_PORT=%q\n' "${pepew_proxy_port}"
} > "${pepew_tmp_conf}"
chmod 600 "${pepew_tmp_conf}"
mv -f "${pepew_tmp_conf}" "${pepew_conf_file}"

{
  echo "Miner: ${CUSTOM_NAME:-PepeW-Miner-v1.0.3-HiveOS}"
  echo "Version: ${CUSTOM_VERSION:-1.0.3}"
  echo "Directory: ${pepew_package_dir}"
  echo "Upstream pool: configured"
  echo "Wallet/template: configured"
  echo "Password: configured"
  echo "Local proxy: stratum+tcp://127.0.0.1:${pepew_proxy_port}"
  echo "Extra arguments: ${pepew_extra_raw:+configured}"
  echo "Status file: ${pepew_package_dir}/miner-status.env"
} > "${pepew_setup_file}"

unset pepew_args pepew_extra 2>/dev/null || true
