#!/usr/bin/env bash
set -u

# Sourced by HiveOS' generic /hive/miners/custom/h-config.sh.
# It writes one shared configuration that h-run.sh expands into one isolated
# miner/proxy pair per selected NVIDIA GPU.

pepew_package_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
pepew_conf_file="${CUSTOM_CONFIG_FILENAME:-${pepew_package_dir}/config.txt}"
pepew_setup_file="${pepew_package_dir}/setup.txt"

if [[ -z "${CUSTOM_URL:-}" && -r /hive-config/wallet.conf ]]; then
  # shellcheck disable=SC1091
  source /hive-config/wallet.conf
fi

pepew_pool="${CUSTOM_URL:-}"
pepew_user="${CUSTOM_TEMPLATE:-}"
pepew_pass="${CUSTOM_PASS:-x}"
pepew_extra_raw="${CUSTOM_USER_CONFIG:-}"
pepew_proxy_port_base="${PEPEW_PROXY_PORT_BASE:-49333}"
pepew_devices="${PEPEW_DEVICES:-all}"
pepew_diagnostic="${PEPEW_DIAGNOSTIC:-0}"

if [[ -z "${pepew_pool}" ]]; then
  echo "HiveOS pool URL is missing (CUSTOM_URL)" >&2
  return 1 2>/dev/null || exit 1
fi
if [[ -z "${pepew_user}" ]]; then
  echo "HiveOS wallet/template is missing (CUSTOM_TEMPLATE)" >&2
  return 1 2>/dev/null || exit 1
fi
if [[ ! "${pepew_proxy_port_base}" =~ ^[0-9]+$ ]] ||
   (( pepew_proxy_port_base < 1024 || pepew_proxy_port_base > 65400 )); then
  echo "Invalid PEPEW_PROXY_PORT_BASE: ${pepew_proxy_port_base}" >&2
  return 1 2>/dev/null || exit 1
fi
if [[ "${pepew_devices}" != "all" && ! "${pepew_devices}" =~ ^[0-9]+(,[0-9]+)*$ ]]; then
  echo "PEPEW_DEVICES must be 'all' or a comma-separated GPU index list" >&2
  return 1 2>/dev/null || exit 1
fi
if [[ ! "${pepew_diagnostic}" =~ ^[01]$ ]]; then
  echo "PEPEW_DIAGNOSTIC must be 0 or 1" >&2
  return 1 2>/dev/null || exit 1
fi

pepew_extra=()
if [[ -n "${pepew_extra_raw}" ]]; then
  # HiveOS exposes this as an expert field. Preserve quoted argument groups.
  eval "pepew_extra=( ${pepew_extra_raw} )"
  for pepew_token in "${pepew_extra[@]}"; do
    case "${pepew_token}" in
      -o|--pool|-O|--pool2|-u|--user|-p|--pass|--diagnostic-log)
        echo "Reserved option is managed by the multi-GPU wrapper: ${pepew_token}" >&2
        return 1 2>/dev/null || exit 1
        ;;
    esac
  done
fi

mkdir -p "${pepew_package_dir}"
pepew_tmp_conf="${pepew_conf_file}.tmp.$$"
{
  echo "# Generated by PepeW Miner v1.0.4 HiveOS integration"
  printf 'PEPEPOW_UPSTREAM=%q\n' "${pepew_pool}"
  printf 'PEPEPOW_USER=%q\n' "${pepew_user}"
  printf 'PEPEPOW_PASS=%q\n' "${pepew_pass}"
  printf 'PEPEPOW_PROXY_PORT_BASE=%q\n' "${pepew_proxy_port_base}"
  printf 'PEPEPOW_DEVICES=%q\n' "${pepew_devices}"
  printf 'PEPEPOW_DIAGNOSTIC=%q\n' "${pepew_diagnostic}"
  printf 'PEPEPOW_EXTRA_ARGS=('
  printf ' %q' "${pepew_extra[@]}"
  echo ' )'
} > "${pepew_tmp_conf}"
chmod 600 "${pepew_tmp_conf}"
mv -f "${pepew_tmp_conf}" "${pepew_conf_file}"

{
  echo "Miner: ${CUSTOM_NAME:-PepeW-Miner-v1.0.4-HiveOS}"
  echo "Version: ${CUSTOM_VERSION:-1.0.4}"
  echo "Directory: ${pepew_package_dir}"
  echo "Mode: one isolated miner and proxy process per selected NVIDIA GPU"
  echo "Selected GPUs: ${pepew_devices}"
  echo "Proxy port base: ${pepew_proxy_port_base}"
  echo "Upstream pool: configured"
  echo "Wallet/template: configured"
  echo "Password: configured"
  echo "Extra arguments: ${pepew_extra_raw:+configured}"
  echo "Per-GPU status: ${pepew_package_dir}/gpu<N>/miner-status.env"
} > "${pepew_setup_file}"

unset pepew_extra pepew_token 2>/dev/null || true
