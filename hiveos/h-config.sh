#!/usr/bin/env bash

if [[ -r /hive-config/wallet.conf ]]; then
  # shellcheck disable=SC1091
  source /hive-config/wallet.conf
fi

miner_dir="${MINER_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)}"
conf_file="${CUSTOM_CONFIG_FILENAME:-${miner_dir}/config.txt}"
setup_file="${miner_dir}/setup.txt"

pool="${CUSTOM_URL:-}"
user="${CUSTOM_TEMPLATE:-}"
pass="${CUSTOM_PASS:-x}"
extra_raw="${CUSTOM_USER_CONFIG:-}"

if [[ -z "${pool}" ]]; then
  echo "HiveOS pool URL is missing (CUSTOM_URL)" >&2
  return 1 2>/dev/null || exit 1
fi
if [[ -z "${user}" ]]; then
  echo "HiveOS wallet/template is missing (CUSTOM_TEMPLATE)" >&2
  return 1 2>/dev/null || exit 1
fi

args=("-o" "${pool}" "-u" "${user}" "-p" "${pass}" "--pepepow" "--diagnostic")

if [[ -n "${extra_raw}" ]]; then
  eval "extra=( ${extra_raw} )"
  args+=("${extra[@]}")
fi

mkdir -p "$(dirname "${conf_file}")"
{
  echo "# Generated by HiveOS h-config.sh"
  printf 'PEPEPOW_ARGS=('
  printf ' %q' "${args[@]}"
  echo ' )'
} > "${conf_file}"

{
  echo "Pool: ${pool}"
  echo "User: ${user}"
  echo "Password: ${pass}"
  echo "Extra config: ${extra_raw}"
  echo "Diagnostic mode: enabled"
  printf 'Final command: ./pepepowminer'
  printf ' %q' "${args[@]}"
  echo
} > "${setup_file}"

export PEPEPOW_CONFIG_FILE="${conf_file}"
